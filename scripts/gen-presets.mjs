#!/usr/bin/env node
/**
 * Generates `src/client/presets.ts` from Chrome DevTools' EmulatedDevices.ts.
 *
 * Source: https://github.com/ChromeDevTools/devtools-frontend
 *         front_end/models/emulation/EmulatedDevices.ts (BSD-3-Clause)
 *
 * Usage:
 *   node scripts/gen-presets.mjs [path-to-EmulatedDevices.ts]
 * Without a path the pinned upstream raw file is downloaded.
 */
import { readFileSync, writeFileSync } from 'node:fs'

const PINNED = 'https://raw.githubusercontent.com/ChromeDevTools/devtools-frontend/main/front_end/models/emulation/EmulatedDevices.ts'
const OUT = new URL('../src/client/presets.ts', import.meta.url)

// Titles we ship. Everything else stays upstream.
const WANTED = [
  'iPhone SE', 'iPhone 15', 'iPhone 15 Pro Max', 'iPhone 16 Pro',
  'Pixel 9', 'Samsung Galaxy A55', 'Galaxy Z Fold 6',
  'iPad Mini', 'iPad Pro 13', 'Surface Pro 10',
  'Nest Hub Max',
]

const GROUP = {
  phone: 'phone',
  tablet: 'tablet',
  notebook: 'laptop',
  'smart-display': 'desktop',
}

// Generic desktop/laptop viewports are not device entries in Chrome.
const EXTRA = [
  { id: 'laptop-1280', group: 'laptop', title: 'Laptop 1280×800', width: 1280, height: 800, dpr: 2 },
  { id: 'desktop-1440', group: 'desktop', title: 'Desktop 1440×900', width: 1440, height: 900, dpr: 1 },
  { id: 'desktop-1920', group: 'desktop', title: 'Desktop 1920×1080', width: 1920, height: 1080, dpr: 1 },
]

const source = process.argv[2]
  ? readFileSync(process.argv[2], 'utf8')
  : await (await fetch(PINNED)).text()

const start = source.indexOf('const emulatedDevices = [')
const end = source.indexOf('\n];', start)
if (start < 0 || end < 0) throw new Error('emulatedDevices array not found')
const literal = source
  .slice(start + 'const emulatedDevices = '.length, end + 2)
  .replace(/^\s*\/\/.*$/gm, '')

const UIStrings = {
  laptopWithTouch: 'Laptop with touch',
  laptopWithHiDPIScreen: 'Laptop with HiDPI screen',
  laptopWithMDPIScreen: 'Laptop with MDPI screen',
}
const devices = new Function(
  'i18nLazyString',
  'UIStrings',
  `return ${literal}`,
)((v) => v, UIStrings)

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')

const picked = []
for (const d of devices) {
  if (!WANTED.includes(d.title)) continue
  const mode = (d.modes ?? []).find((m) => m.orientation === 'vertical') ?? {}
  const item = {
    id: slug(d.title),
    group: GROUP[d.type] ?? 'phone',
    title: d.title,
    width: d.screen.vertical.width,
    height: d.screen.vertical.height,
    dpr: d.screen['device-pixel-ratio'],
    mobile: (d.capabilities ?? []).includes('mobile'),
    touch: (d.capabilities ?? []).includes('touch'),
    ua: d['user-agent'],
  }
  if (mode.cutout) {
    item.cutout = {
      shape: mode.cutout.shape ?? 'notch',
      x: mode.cutout.x ?? 0,
      y: mode.cutout.y ?? 0,
      width: mode.cutout.width ?? 0,
      height: mode.cutout.height ?? 0,
      radius: mode.cutout['border-radius'] ?? 0,
    }
  }
  if (mode['safe-area-insets']) {
    const i = mode['safe-area-insets']
    item.insets = { top: i.top ?? 0, right: i.right ?? 0, bottom: i.bottom ?? 0, left: i.left ?? 0 }
  }
  picked.push(item)
}
picked.sort((a, b) => WANTED.indexOf(a.title) - WANTED.indexOf(b.title))
for (const e of EXTRA) picked.push({ ...e, mobile: false, touch: false })

const banner = `/**
 * Device presets, generated by scripts/gen-presets.mjs — do not edit by hand.
 *
 * Sizes, device-pixel-ratios, user agents, cutouts and safe-area insets come
 * from Chrome DevTools' front_end/models/emulation/EmulatedDevices.ts,
 * Copyright the Chromium Authors, BSD-3-Clause (see NOTICE).
 * "Reference sizes": DPR and touch are metadata here; the plugin emulates the
 * viewport and the user agent, not device pixels or touch input.
 */
`
const body = `export type PresetGroup = 'phone' | 'tablet' | 'laptop' | 'desktop'

export interface Cutout {
  shape: string
  x: number
  y: number
  width: number
  height: number
  radius: number
}

export interface Insets {
  top: number
  right: number
  bottom: number
  left: number
}

export interface Preset {
  id: string
  group: PresetGroup
  title: string
  width: number
  height: number
  dpr: number
  mobile: boolean
  touch: boolean
  ua?: string
  cutout?: Cutout
  insets?: Insets
}

export const GROUP_LABEL: Record<PresetGroup, { zh: string; en: string }> = {
  phone: { zh: '手机', en: 'Phone' },
  tablet: { zh: '平板', en: 'Tablet' },
  laptop: { zh: '笔记本', en: 'Laptop' },
  desktop: { zh: '桌面', en: 'Desktop' },
}

export const PRESETS: Preset[] = ${JSON.stringify(picked, null, 2)}

export const PRESET_BY_ID = new Map(PRESETS.map((p) => [p.id, p]))
`
writeFileSync(OUT, banner + body)
console.log(`wrote ${picked.length} presets to ${OUT.pathname}`)
