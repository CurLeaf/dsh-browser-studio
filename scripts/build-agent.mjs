#!/usr/bin/env node
/** Bundles the injected page agent into a string the client can ship. */
import { build } from 'esbuild'
import { writeFileSync, mkdirSync } from 'node:fs'

const result = await build({
  entryPoints: ['src/agent/index.ts'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  write: false,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
})

const code = result.outputFiles[0].text
mkdirSync('src/generated', { recursive: true })
writeFileSync(
  'src/generated/agent-bundle.ts',
  `// Generated by scripts/build-agent.mjs — do not edit.\nexport const AGENT_BOOT = ${JSON.stringify(code)}\n`,
)
console.log(`agent bundle: ${(code.length / 1024).toFixed(1)} KiB`)
